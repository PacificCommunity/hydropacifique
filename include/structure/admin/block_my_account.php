Modal layout, opened by clicking the user block (.bando-user) in the
top header (which include() this file at render time).

Included from header.php, which is itself rendered by pages that have
already called application_top.php. We therefore reuse the globals
that application_top sets up:
  - $id_user             — session-resolved current user id
  - $login_user / $email_user / $prenom_user / $nom_user / $info_user
                         — session-cached user fields
  - $sql_link            — open DB connection
  - $languages_array     — supported languages
  - $_SESSION['csrf_token'] — generated by any admin page; we generate
                              it here as a fallback for the (rare) case
                              where the user opens the popup before
                              visiting an admin page.

Editable fields:
  - Last name        (nom)
  - First name       (prenom)
  - Additional info  (info)
  - Language         (lang)

Read-only fields (intentionally displayed but locked):
  - Login            (login)        — identity, must remain stable
  - Email            (email)        — used for password reset etc.
  - Service          (id_service)   — assigned by admins only

The save endpoint (process_my_account_save.php) ignores any attempt to
post the read-only fields, so a manually crafted request can't escape
the restriction client-side.
----------------------------------------
*/

// CSRF token — reuse the one already in session if present; create a
// new one only if no other admin page has done so. Single source of
// truth shared with process_my_account_save.php's verification.
if (empty($_SESSION['csrf_token'])) {
    $_SESSION['csrf_token'] = bin2hex(random_bytes(32));
}

// Service label — application_top doesn't load it (no need on most
// pages), so we do a tiny lookup here for the read-only display.
$myacc_service_label = '';
if (isset($id_service_user) && (int) $id_service_user > 0)
{
    $sv_query = tep_db_query(
        $sql_link,
        "SELECT name, description FROM " . TABLE_SERVICE
        . " WHERE id_service = " . (int) $id_service_user . " LIMIT 1"
    );
    $sv_tab = tep_db_fetch_array($sv_query);
    if ($sv_tab)
    {
        $myacc_service_label = html_entity_decode($sv_tab['name'] ?? '');
        if (!empty($sv_tab['description']))
        {
            $myacc_service_label .= ' - ' . html_entity_decode($sv_tab['description']);
        }
    }
}

// Login / email / language — application_top's getAdminInfo() exposes
// nom / prenom / info but the contents of $tab_session for the other
// fields is implementation-dependent (changed across versions of the
// helper). To stay safe we re-read these three values straight from
// TABLE_USER here. Same connection, single row, negligible cost.
$myacc_login = '';
$myacc_email = '';
$myacc_lang  = LANGUAGE_TERRITOIRE;

if (isset($id_user) && (int) $id_user > 0)
{
    $u_query = tep_db_query(
        $sql_link,
        "SELECT login, email, lang FROM " . TABLE_USER
        . " WHERE id = " . (int) $id_user . " LIMIT 1"
    );
    $u_tab = tep_db_fetch_array($u_query);
    if ($u_tab)
    {
        $myacc_login = html_entity_decode($u_tab['login'] ?? '');
        $myacc_email = html_entity_decode($u_tab['email'] ?? '');
        if (!empty($u_tab['lang']))
        {
            $myacc_lang = $u_tab['lang'];
        }
    }
}
