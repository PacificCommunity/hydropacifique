<script>
    // -----------------------------------------------
    // Personal-account popup — open / close / save handlers
    //
    // Lifecycle:
    //  - .bando-user (in header.php) has an onClick that calls
    //    openMyAccount() — defined here so the wiring stays in one place.
    //  - The popup uses display:flex when visible to center its child;
    //    swapped back to display:none when closed.
    //  - Save POSTs to process_my_account_save.php and refreshes the
    //    header text (name / role) on success without a page reload.
    //
    // The DOM lookups all happen inside the handlers (not at load time)
    // because this block can be included before some of the referenced
    // elements have been rendered. Defensive null-checks throughout.
    // -----------------------------------------------

    (function() {

        var modal       = document.getElementById('block_my_account');
        var closeBtn    = document.getElementById('myacc_close');
        var cancelBtn   = document.getElementById('myacc_cancel');
        var saveBtn     = document.getElementById('myacc_save');
        var infoBanner  = document.getElementById('myacc_info');
        var form        = document.getElementById('formMyAccount');

        if (!modal) { return; }

        // -----------------------------------------------
        // openMyAccount() / closeMyAccount()
        // Exposed on window so the header onClick can find them.

        window.openMyAccount = function() {
            // Clear any stale feedback from a previous open
            if (infoBanner) {
                infoBanner.style.display = 'none';
                infoBanner.innerHTML     = '';
            }
            // 'block' is enough — the inner card centers itself via
            // top/left + transform, independent of the overlay's display.
            modal.style.display = 'block';
            // Focus first editable field for a quicker edit flow
            var firstField = document.getElementById('myacc_nom');
            if (firstField) { firstField.focus(); }
        };

        window.closeMyAccount = function() {
            modal.style.display = 'none';
        };


        // -----------------------------------------------
        // Close interactions

        if (closeBtn)  { closeBtn.addEventListener('click',  window.closeMyAccount); }
        if (cancelBtn) { cancelBtn.addEventListener('click', window.closeMyAccount); }

        // Click on the dark overlay (but NOT on the inner card) closes too
        modal.addEventListener('click', function(e) {
            if (e.target === modal) { window.closeMyAccount(); }
        });

        document.addEventListener('keydown', function(e) {
            if (e.key === 'Escape' && modal.style.display !== 'none') {
                window.closeMyAccount();
            }
        });


        // -----------------------------------------------
        // Save handler

        function showBanner(msg, isError) {
            if (!infoBanner) { return; }
            infoBanner.innerHTML        = msg;
            infoBanner.style.border     = isError ? '2px solid #930000' : '2px solid #09886d';
            infoBanner.style.background = isError ? '#fdecec'           : '#ecf7ef';
            infoBanner.style.color      = isError ? '#930000'           : '#0a7d34';
            infoBanner.style.display    = 'block';
        }

        function refreshHeaderUser() {
            // Soft-update the user block in the top header so the
            // freshly saved name appears immediately, without a reload.
            var nom    = document.getElementById('myacc_nom').value.trim();
            var prenom = document.getElementById('myacc_prenom').value.trim();
            var info   = document.getElementById('myacc_info_user').value.trim();

            var nameEl = document.querySelector('.bando-user .name');
            var roleEl = document.querySelector('.bando-user .role');
            if (nameEl) { nameEl.textContent = (prenom + ' ' + nom).trim(); }
            if (roleEl) { roleEl.textContent = info; }

            // Avatar initials — first letter of first + last name
            var avatarEl = document.querySelector('.bando-user .avatar');
            if (avatarEl) {
                var ip = (prenom.charAt(0) || '').toUpperCase();
                var in_ = (nom.charAt(0) || '').toUpperCase();
                avatarEl.textContent = ip + in_;
            }
        }

        if (saveBtn) {
            saveBtn.addEventListener('click', function() {
                if (!form) { return; }

                // Disable button to prevent double-submit
                saveBtn.disabled = true;
                saveBtn.style.opacity = '0.6';
                saveBtn.style.cursor = 'wait';

                var formData = new FormData(form);

                var xhr = new XMLHttpRequest();
                xhr.open('POST', 'include/structure/admin/process_my_account_save.php', true);

                xhr.onreadystatechange = function() {
                    if (xhr.readyState !== 4) { return; }

                    // Re-enable the button no matter what
                    saveBtn.disabled = false;
                    saveBtn.style.opacity = '';
                    saveBtn.style.cursor = '';

                    if (xhr.status === 200) {
                        try {
                            var r = JSON.parse(xhr.responseText);
                            showBanner(r.msg_info || '', !!r.erreur);

                            if (!r.erreur) {
                                refreshHeaderUser();
                                // If the language changed, reload the page so
                                // the new translations apply throughout the UI.
                                if (r.lang_changed) {
                                    setTimeout(function() {
                                        window.location.reload();
                                    }, 1200);
                                }
                            }
                        } catch (e) {
                            showBanner('<?php echo TEXT_MYACC_ERR_UNEXPECTED; ?>', true);
                        }
                    } else {
                        showBanner('<?php echo TEXT_MYACC_ERR_HTTP; ?> ' + xhr.status, true);
                    }
                };

                xhr.send(formData);
            });
        }

    })();
</script>